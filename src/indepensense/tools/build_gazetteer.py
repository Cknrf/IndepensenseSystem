"""Build the place-name list that misheard destinations are corrected against.

    zstd -dc photon-dump-philippines-1.0-latest.jsonl.zst \\
      | python -m indepensense.tools.build_gazetteer --province Batangas

Reads a Photon JSONL dump on stdin and writes every distinct place name
in one province to `config.GAZETTEER_PATH`, one per line. The dump is the
same file the local Photon index is imported from (see docs/photon.md),
so every name in the list is one Photon can find — a correction can
never point at a place the geocoder has not heard of.

Run it on the Mac, not the Pi: the dump is ~90 MB compressed and the
output is a few hundred kilobytes of text, committed to the repo so the
Pi receives it with everything else and the thesis can cite the exact
list in use. Re-run it when the Photon index is rebuilt from a newer dump.

**Why only `name`, not `alt_name`, `old_name` and the rest.** The
primary name is the one Photon is certain to match on. The alternatives
are a few hundred entries in a province of ~16,000 names — not enough
to justify depending on which of them a given Photon build indexes.

**Why one province rather than the country.** The Philippines is ~830k
places. Every extra name is another near neighbour a misheard word can
be pulled towards, and the list is searched on every miss. The wearable
is deployed in Batangas; another area is a rebuild with `--province`.

The province is read from the dump's `address.state`, which is where
Photon records the OSM admin level 4 boundary — the province, in the
Philippines.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Iterable
from pathlib import Path

from indepensense.config import GAZETTEER_PATH


def place_names(lines: Iterable[str], province: str) -> tuple[set[str], str | None]:
    """Collect the primary names of every place in `province`.

    Returns the names and the dump's data timestamp, read from its
    header record, so the output can say which snapshot it came from.
    Records that are not places, or have no name, are skipped.
    """
    names: set[str] = set()
    timestamp: str | None = None
    for line in lines:
        record = json.loads(line)
        kind = record.get("type")
        if kind == "NominatimDumpFile":
            timestamp = record.get("content", {}).get("data_timestamp")
            continue
        if kind != "Place":
            continue
        for place in record.get("content", []):
            if (place.get("address") or {}).get("state") != province:
                continue
            name = ((place.get("name") or {}).get("name") or "").strip()
            if name:
                names.add(name)
    return names, timestamp


def render(names: set[str], province: str, timestamp: str | None) -> str:
    """The file's text: a provenance header, then the names sorted."""
    header = [
        "# Place names for the gazetteer (routing/gazetteer.py).",
        f"# Province: {province}. Photon dump data timestamp: {timestamp or 'unknown'}.",
        "# Generated by `python -m indepensense.tools.build_gazetteer`; do not edit by hand.",
    ]
    return "\n".join(header + sorted(names)) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--province", required=True,
        help="province as it appears in the dump's address.state, e.g. Batangas",
    )
    parser.add_argument(
        "--out", type=Path, default=GAZETTEER_PATH,
        help=f"output file (default: {GAZETTEER_PATH})",
    )
    args = parser.parse_args(argv)

    names, timestamp = place_names(sys.stdin, args.province)
    if not names:
        # Almost always a misspelt province. An empty list would load
        # cleanly and silently correct nothing, so refuse to write it.
        print(f"No places found in province {args.province!r}.", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(names, args.province, timestamp), encoding="utf-8")
    print(f"Wrote {len(names)} names to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
